/**
 * DAX-4-A3 (DE-28): the pause survives a REAL process restart. The built signer is started as a process against a fake Accumulate
 * node and a fake policy engine (both in this test process, async, no spawnSync), paused over its admin API, KILLED, started again
 * from the same state directory, and shown to still hold: the health probe says paused, GET /v1/admin/pause names who and why, and
 * a transaction triggered after the restart is NOT signed (the fake node sees no submit). Seat and subject scopes, a resume of the
 * wrong scope refused by name, a hard kill and a graceful stop. FICTIONAL parties; the signing key is a throwaway generated by
 * the process (allow_ephemeral), the secrets below are random values made for this run and never written to the repository.
 */
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import http from 'node:http';
import net from 'node:net';
import { spawn, type ChildProcess } from 'node:child_process';
import { createHmac, randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { intentBody, subjectClaim } from './support/binding-fixtures.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SIGNER_PAGE = 'acc://o.acme/book/1';
const SEAT = 'seat:fic-treasury';
const BY = 'seat:fic-operator';
const WHY = 'FICTIONAL: suspected key misuse, stopping';
const SUBJECT_ONE = 'acc://agent-one.fic-grantor.acme';
const SUBJECT_TWO = 'acc://agent-two.fic-grantor.acme';
const TXS = { control: '01'.repeat(32), seatHeld: '02'.repeat(32), subjectHeld: '03'.repeat(32), subjectFree: '04'.repeat(32), afterResume: '05'.repeat(32) };

const ADMIN_KEY = randomBytes(12).toString('hex');
const HOOK_KEY = randomBytes(12).toString('hex');

let tmp: string;
let bundle: string;
let acc: http.Server;
let engine: http.Server;
let accPort = 0;
let enginePort = 0;
let healthPort = 0;
const submits: unknown[] = [];
const pending = new Map<string, unknown>();
const children: ChildProcess[] = [];

const listen = (s: http.Server): Promise<number> => new Promise((r) => s.listen(0, '127.0.0.1', () => r((s.address() as net.AddressInfo).port)));
const freePort = (): Promise<number> => new Promise((res) => { const s = net.createServer(); s.listen(0, '127.0.0.1', () => { const p = (s.address() as net.AddressInfo).port; s.close(() => res(p)); }); });
const sleep = (ms: number): Promise<void> => new Promise((r) => setTimeout(r, ms));
const body = (req: http.IncomingMessage): Promise<string> => new Promise((r) => { const c: Buffer[] = []; req.on('data', (x) => c.push(x)); req.on('end', () => r(Buffer.concat(c).toString('utf8'))); });

beforeAll(async () => {
  tmp = mkdtempSync(join(tmpdir(), 'dax4s-proc-'));
  // The real build (src/index.ts, the same options as scripts/build.mjs) under its own name, so no other test's dist/signer.cjs is touched.
  mkdirSync(join(ROOT, 'dist'), { recursive: true });
  bundle = join(ROOT, 'dist', `pause-process-${process.pid}.cjs`);
  await build({ entryPoints: [join(ROOT, 'src', 'index.ts')], bundle: true, platform: 'node', target: 'node20', format: 'cjs', outfile: bundle, external: ['pino', 'pino-pretty', 'pkcs11js'], logLevel: 'silent' });

  acc = http.createServer(async (req, res) => {
    const rpc = JSON.parse((await body(req)) || '{}') as { method?: string; params?: { scope?: string } };
    const reply = (result: unknown) => { res.writeHead(200, { 'content-type': 'application/json' }); res.end(JSON.stringify({ jsonrpc: '2.0', id: 1, result })); };
    if (rpc.method === 'submit') { submits.push(rpc.params); return reply({ success: true, status: { delivered: true } }); }
    const scope = rpc.params?.scope ?? '';
    const m = /^acc:\/\/([0-9a-f]{64})@/.exec(scope);
    if (m) { const tx = pending.get(m[1]!); return tx ? reply({ recordType: 'message', status: 'pending', message: { transaction: tx } }) : (res.writeHead(200, { 'content-type': 'application/json' }), res.end(JSON.stringify({ jsonrpc: '2.0', id: 1, error: { message: 'not found' } }))); }
    return reply({ account: { version: 1, creditBalance: 100, keys: [] } }); // the signer page
  });
  engine = http.createServer(async (req, res) => { await body(req); res.writeHead(200, { 'content-type': 'application/json' }); res.end(JSON.stringify({ decision: 'approve', reason: 'FICTIONAL approval' })); });
  accPort = await listen(acc);
  enginePort = await listen(engine);
  healthPort = await freePort();
  const mk = (subject?: string) => ({ header: { principal: 'acc://fic-principal.acme/tokens' }, body: intentBody(subject ? { subject: subjectClaim(subject) } : {}) });
  pending.set(TXS.control, mk());
  pending.set(TXS.seatHeld, mk());
  pending.set(TXS.subjectHeld, mk(SUBJECT_ONE));
  pending.set(TXS.subjectFree, mk(SUBJECT_TWO));
  pending.set(TXS.afterResume, mk(SUBJECT_ONE));
  const state = join(tmp, 'state');
  mkdirSync(state, { recursive: true });
  writeFileSync(join(tmp, 'config.yaml'), [
    'wallet:',
    '  org_id: fic-org',
    `  accumulate_endpoints: ["http://127.0.0.1:${accPort}/v3"]`,
    `  signer_url: "${SIGNER_PAGE}"`,
    `  seat: "${SEAT}"`,
    '  allow_unverified_signer: true',
    'signer: { provider: "local", local: { allow_ephemeral: true } }',
    `policy: { url: "http://127.0.0.1:${enginePort}/decision", auth: "none" }`,
    'trigger:',
    '  webhook: { enabled: true, hmac_secret: "env:FIC_HOOK_KEY" }',
    '  poller: { enabled: false }',
    'behavior: { submit_reject_vote: true }',
    `health: { bind: "127.0.0.1:${healthPort}" }`,
    'admin: { api_key: "env:FIC_ADMIN_KEY" }',
    `store: { path: "${join(state, 'store.json').replace(/\\/g, '/')}" }`,
  ].join('\n'));
}, 120_000);

afterAll(async () => {
  for (const c of children) if (c.exitCode === null) c.kill('SIGKILL');
  acc?.close(); engine?.close();
  await sleep(300);
  if (bundle && existsSync(bundle)) rmSync(bundle, { force: true });
  if (tmp) rmSync(tmp, { recursive: true, force: true });
});

function startSigner(): { child: ChildProcess; log: string[] } {
  const log: string[] = [];
  const child = spawn(process.execPath, [bundle, join(tmp, 'config.yaml')], { env: { ...process.env, FIC_ADMIN_KEY: ADMIN_KEY, FIC_HOOK_KEY: HOOK_KEY }, stdio: ['ignore', 'pipe', 'pipe'] });
  child.stdout!.on('data', (d) => log.push(String(d)));
  child.stderr!.on('data', (d) => log.push(String(d)));
  children.push(child);
  return { child, log };
}
async function waitHealthy(proc: { child: ChildProcess; log: string[] }): Promise<void> {
  for (let i = 0; i < 240; i++) {
    if (proc.child.exitCode !== null) throw new Error('the signer exited at start: ' + proc.log.join('').slice(-600).replace(new RegExp(ADMIN_KEY, 'g'), '***'));
    try { const r = await fetch(`http://127.0.0.1:${healthPort}/healthz`); if (r.status === 200 || r.status === 503) return; } catch { /* not listening yet */ }
    await sleep(250);
  }
  throw new Error('the signer did not become healthy: ' + proc.log.join('').slice(-600).replace(new RegExp(ADMIN_KEY, 'g'), '***'));
}
const stop = (p: { child: ChildProcess }, signal: NodeJS.Signals): Promise<void> => new Promise((r) => { if (p.child.exitCode !== null) return r(); p.child.once('exit', () => r()); p.child.kill(signal); });
const admin = async (method: string, path: string, json?: unknown) => {
  const r = await fetch(`http://127.0.0.1:${healthPort}${path}`, { method, headers: { 'x-api-key': ADMIN_KEY, ...(json === undefined ? {} : { 'content-type': 'application/json' }) }, ...(json === undefined ? {} : { body: JSON.stringify(json) }) });
  return { status: r.status, json: (await r.json()) as any };
};
async function trigger(tx: string): Promise<void> {
  const b = JSON.stringify({ tx_hash: tx, signer_url: SIGNER_PAGE });
  const ts = String(Date.now());
  const sig = `t=${ts},v1=${createHmac('sha256', HOOK_KEY).update(`${ts}.${b}`).digest('hex')}`;
  const r = await fetch(`http://127.0.0.1:${healthPort}/v1/pending`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-signer-signature': sig }, body: b });
  expect(r.status).toBe(202);
}
/** waits for the signer to have handled the transaction: its row is no longer `discovered`/missing, then returns the row */
async function settle(tx: string): Promise<{ status: string; lastError?: string }> {
  for (let i = 0; i < 120; i++) {
    const r = await admin('GET', `/v1/requests/${tx}`);
    if (r.status === 200 && ['signed', 'rejected', 'error'].includes(r.json.request.status)) return r.json.request;
    if (r.status === 200 && r.json.request.status === 'awaiting_policy' && r.json.request.lastError) return r.json.request;
    await sleep(250);
  }
  throw new Error(`the signer did not settle ${tx}`);
}
const paused = async (): Promise<boolean> => (await (await fetch(`http://127.0.0.1:${healthPort}/healthz`)).json() as { paused: boolean }).paused;

describe('the pause survives a real process restart (DAX-4-A3, DE-25, DE-28)', () => {
  it('seat pause: signs before it, is KILLED while paused, and after the restart still holds and signs nothing', async () => {
    const first = startSigner();
    await waitHealthy(first);
    expect(await paused()).toBe(false);
    await trigger(TXS.control);
    expect((await settle(TXS.control)).status).toBe('signed');
    expect(submits).toHaveLength(1); // the control: this signer, this config, signs

    expect((await admin('POST', '/v1/admin/pause', { scope: 'seat', id: SEAT, by: BY, reason: WHY })).status).toBe(200);
    expect(await paused()).toBe(true);
    await stop(first, 'SIGKILL'); // a hard kill: no shutdown hook runs

    const second = startSigner();
    await waitHealthy(second);
    expect(await paused()).toBe(true);
    const got = await admin('GET', '/v1/admin/pause');
    expect(got.json.pauses).toEqual([expect.objectContaining({ scope: 'seat', id: SEAT, by: BY, reason: WHY })]);
    await trigger(TXS.seatHeld);
    const row = await settle(TXS.seatHeld);
    expect(row).toMatchObject({ status: 'awaiting_policy', lastError: 'paused' });
    expect(submits).toHaveLength(1); // nothing was signed after the restart
    await stop(second, 'SIGTERM'); // a stop, not a kill
  }, 180_000);

  it('a SECOND restart still holds; a resume of the wrong scope is refused by name; the right one lifts it', async () => {
    const third = startSigner();
    await waitHealthy(third);
    expect(await paused()).toBe(true);
    expect(await admin('POST', '/v1/admin/resume', { scope: 'subject', id: SUBJECT_ONE, by: BY, reason: WHY })).toMatchObject({ status: 409, json: { error: 'not_paused' } });
    expect(await paused()).toBe(true);
    expect((await admin('POST', '/v1/admin/resume', { scope: 'seat', id: SEAT, by: BY, reason: WHY })).json.paused).toBe(false);
    expect(await paused()).toBe(false);
    await stop(third, 'SIGKILL');
    const fourth = startSigner();
    await waitHealthy(fourth);
    expect(await paused()).toBe(false); // a resume is as durable as a pause
    await stop(fourth, 'SIGKILL');
  }, 180_000);

  it('a subject pause survives a restart: that subject is held, another subject and the seat still sign', async () => {
    const a = startSigner();
    await waitHealthy(a);
    expect((await admin('POST', '/v1/admin/pause', { scope: 'subject', id: SUBJECT_ONE, by: BY, reason: WHY })).status).toBe(200);
    await stop(a, 'SIGKILL');
    const b = startSigner();
    await waitHealthy(b);
    const before = submits.length;
    await trigger(TXS.subjectHeld);
    expect(await settle(TXS.subjectHeld)).toMatchObject({ status: 'awaiting_policy', lastError: 'paused' });
    expect(submits).toHaveLength(before);
    await trigger(TXS.subjectFree);
    expect((await settle(TXS.subjectFree)).status).toBe('signed');
    expect(submits).toHaveLength(before + 1);
    // a resume of the SEAT does not lift the subject pause
    expect(await admin('POST', '/v1/admin/resume', { scope: 'seat', id: SEAT, by: BY, reason: WHY })).toMatchObject({ status: 409 });
    expect((await admin('POST', '/v1/admin/resume', { scope: 'subject', id: SUBJECT_ONE, by: BY, reason: WHY })).json.paused).toBe(false);
    await trigger(TXS.afterResume);
    expect((await settle(TXS.afterResume)).status).toBe('signed');
    await stop(b, 'SIGKILL');
  }, 180_000);
});
